package com.bookstore.support;

import com.bookstore.api.config.ApiConfig;
import org.junit.platform.launcher.TestExecutionListener;
import org.junit.platform.launcher.TestPlan;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.Properties;

public class AllureReportMetadataListener implements TestExecutionListener {

    private static final System.Logger LOGGER = System.getLogger(AllureReportMetadataListener.class.getName());
    private static final String RESULTS_DIRECTORY_PROPERTY = "allure.results.directory";
    private static final String DEFAULT_RESULTS_DIRECTORY = "target/allure-results";
    private static final String CATEGORIES_RESOURCE = "allure/categories.json";

    @Override
    public void testPlanExecutionStarted(TestPlan testPlan) {
        Path resultsDirectory = Paths.get(System.getProperty(RESULTS_DIRECTORY_PROPERTY, DEFAULT_RESULTS_DIRECTORY));
        try {
            Files.createDirectories(resultsDirectory);
            writeEnvironment(resultsDirectory.resolve("environment.properties"));
            copyCategories(resultsDirectory.resolve("categories.json"));
        } catch (IOException e) {
            LOGGER.log(System.Logger.Level.WARNING, "Could not write Allure report metadata", e);
        }
    }

    private static void writeEnvironment(Path target) throws IOException {
        ApiConfig config = ApiConfig.get();
        Properties environment = new Properties();
        environment.setProperty("API.Base.URL", config.baseUrl() + config.basePath());
        environment.setProperty("Java.Version", System.getProperty("java.version"));
        environment.setProperty("OS", System.getProperty("os.name") + " " + System.getProperty("os.version"));
        try (OutputStream out = Files.newOutputStream(target)) {
            environment.store(out, "Generated by AllureReportMetadataListener");
        }
    }

    private static void copyCategories(Path target) throws IOException {
        try (InputStream in = AllureReportMetadataListener.class.getClassLoader().getResourceAsStream(CATEGORIES_RESOURCE)) {
            if (in == null) {
                LOGGER.log(System.Logger.Level.WARNING, "'" + CATEGORIES_RESOURCE + "' not found on the classpath");
                return;
            }
            Files.copy(in, target, StandardCopyOption.REPLACE_EXISTING);
        }
    }
}
